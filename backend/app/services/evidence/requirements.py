# 3. Target Reference Validation Helpers
# ------------------------------------------------------------------------------

def _build_entity_map(model: DecisionModel) -> Dict[str, DecisionEntityType]:
    """Builds a lookup mapping entity ID to DecisionEntityType for a DecisionModel."""
    mapping: Dict[str, DecisionEntityType] = {}
    for o in model.objectives:
        mapping[o.id] = DecisionEntityType.OBJECTIVE
    for v in model.variables:
        mapping[v.id] = DecisionEntityType.VARIABLE
    for c in model.constraints:
        mapping[c.id] = DecisionEntityType.CONSTRAINT
    for s in model.stakeholders:
        mapping[s.id] = DecisionEntityType.STAKEHOLDER
    for t in model.tradeoffs:
        mapping[t.id] = DecisionEntityType.TRADEOFF
    for a in model.assumptions:
        mapping[a.id] = DecisionEntityType.ASSUMPTION
    for u in model.unknowns:
        mapping[u.id] = DecisionEntityType.UNKNOWN
    mapping[model.id] = DecisionEntityType.DECISION
    return mapping


def validate_target_reference(
    decision_model: DecisionModel,
    target_id: str,
    target_type: DecisionEntityType,
) -> None:
    """Validates that target_id exists in decision_model and matches target_type.

    Raises:
        ValueError: If target_id is not found or target_type does not match the actual entity type.
    """
    entity_map = _build_entity_map(decision_model)
    if target_id not in entity_map:
        raise ValueError(
            f"Target entity '{target_id}' of type '{target_type.value}' does not exist in DecisionModel '{decision_model.id}'."
        )
    actual_type = entity_map[target_id]
    if target_type != actual_type:
        raise ValueError(
            f"Mismatched target_entity_type for entity '{target_id}': expected '{actual_type.value}', got '{target_type.value}'."
        )


def _is_verifying_user_provided_fact(
    candidate: CandidateEvidenceRequirement,
    model: DecisionModel,
) -> bool:
    """Returns True if candidate is redundantly attempting to prove an established user fact."""
    desc_lower = candidate.description.lower()

    if candidate.target_entity_type == DecisionEntityType.VARIABLE:
        var = next((v for v in model.variables if v.id == candidate.target_entity_id), None)
        if var and var.proposed_provenance == ProvenanceType.USER_PROVIDED and var.proposed_value is not None:
            val_str = str(var.proposed_value).rstrip(".0") if isinstance(var.proposed_value, float) and var.proposed_value.is_integer() else str(var.proposed_value)
            verifying_patterns = [
                f"verify that the proposed value is {val_str}",
                f"verify whether the user proposed a {val_str}",
                f"verify whether the user proposed {val_str}",
                f"verify if the user proposed {val_str}",
                f"verify that the value is {val_str}",
                f"verify that pricing is reduced by {val_str}",
                f"verify that the discount is {val_str}",
                f"verify that the proposed reduction is {val_str}",
                f"prove that the proposed value is {val_str}",
                f"confirm the user wants to reduce by {val_str}",
                f"verify that our startup plans to reduce pricing by {val_str}",
            ]
            if any(p in desc_lower for p in verifying_patterns):
                return True

    elif candidate.target_entity_type == DecisionEntityType.CONSTRAINT:
        cnstr = next((c for c in model.constraints if c.id == candidate.target_entity_id), None)
        if cnstr and cnstr.provenance == ProvenanceType.USER_PROVIDED:
            if any(p in desc_lower for p in ["verify that the user stated", "confirm user constraint", "verify user constraint"]):
                return True

    return False


def _audit_and_reconcile_requirement_kind(
    kind: EvidenceKind,
    description: str,
) -> EvidenceKind:
    """Detects and repairs semantic contradictions between kind and description.

    Guarantees:
    - EXTERNAL_RESEARCH asking for private internal metrics is repaired to INTERNAL_DATA.
    - INTERNAL_DATA asking for public industry benchmarks is repaired to EXTERNAL_RESEARCH.
    - USER_CLARIFICATION asking for published studies is repaired to EXTERNAL_RESEARCH.
    """
    desc_lower = description.lower()

    # Signals indicating private corporate records/data
    internal_signals = [
        "our company's", "our internal", "private current", "internal proprietary",
        "internal records", "our confidential", "internal database", "private internal",
        "internal cac", "internal churn", "internal cost", "our books", "internal data",
    ]
    # Signals indicating public external research/benchmarks
    external_signals = [
        "public saas benchmark", "industry reports", "published studies",
        "academic literature", "market research study", "public benchmark",
        "industry benchmark", "competitor filings", "published research",
        "search published", "external benchmark", "public reports",
    ]

    # Rule 1: EXTERNAL_RESEARCH asking for private internal data -> repair to INTERNAL_DATA
    if kind == EvidenceKind.EXTERNAL_RESEARCH and any(s in desc_lower for s in internal_signals):
        return EvidenceKind.INTERNAL_DATA

    # Rule 2: INTERNAL_DATA asking for public external research -> repair to EXTERNAL_RESEARCH
    if kind == EvidenceKind.INTERNAL_DATA and any(s in desc_lower for s in external_signals):
        return EvidenceKind.EXTERNAL_RESEARCH

    # Rule 3: USER_CLARIFICATION asking for public external research -> repair to EXTERNAL_RESEARCH
    if kind == EvidenceKind.USER_CLARIFICATION and any(s in desc_lower for s in external_signals):
        return EvidenceKind.EXTERNAL_RESEARCH

    return kind


