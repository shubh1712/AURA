# 5. EvidenceRequirementEngine Implementation
# ------------------------------------------------------------------------------

class EvidenceRequirementEngine:
    """Identifies, classifies, and policy-audits empirical evidence requirements from a DecisionModel."""

    def __init__(self, llm_client: LLMClient) -> None:
        """Initializes EvidenceRequirementEngine.

        Args:
            llm_client: Injected LLMClient instance (e.g. FakeLLMClient in tests).
        """
        self.llm_client = llm_client

    def generate_requirements(
        self,
        decision_model: DecisionModel,
        deadline_monotonic: Optional[float] = None,
    ) -> List[EvidenceRequirement]:
        """Analyzes a DecisionModel and produces a deduplicated, validated list of EvidenceRequirement.

        Args:
            decision_model: The canonical DecisionModel to evaluate.
            deadline_monotonic: Optional absolute monotonic deadline for the operation.

        Returns:
            List[EvidenceRequirement] with status=PENDING and strictly enforced query policies.

        Raises:
            ValueError: If target entities are invalid or mismatched.
            LLMError: If upstream LLM generation fails.
        """
        if deadline_monotonic is not None and time.monotonic() >= deadline_monotonic:
            raise LLMTimeoutError("Operation timed out before evidence requirements generation could begin.")

        # 1. Build prompt
        prompt = build_requirements_prompt(decision_model)

        # 2. Invoke structured generation
        try:
            candidate_payload = self.llm_client.generate_structured(
                prompt=prompt,
                response_schema=CandidateRequirementsPayload,
                system_instruction=REQUIREMENTS_SYSTEM_PROMPT,
                deadline_monotonic=deadline_monotonic,
            )
        except TypeError as te:
            if "unexpected keyword argument 'deadline_monotonic'" in str(te):
                candidate_payload = self.llm_client.generate_structured(
                    prompt=prompt,
                    response_schema=CandidateRequirementsPayload,
                    system_instruction=REQUIREMENTS_SYSTEM_PROMPT,
                )
            else:
                raise

        # 3. Policy enforcement, reference validation, and deduplication
        requirements: List[EvidenceRequirement] = []
        seen_targets: Set[tuple[str, EvidenceKind]] = set()
        req_counter = 1

        for candidate in candidate_payload.requirements:
            # Enforce target validation (raises ValueError on invalid reference)
            validate_target_reference(
                decision_model=decision_model,
                target_id=candidate.target_entity_id,
                target_type=candidate.target_entity_type,
            )

            # Enforce user-provided fact guard
            if _is_verifying_user_provided_fact(candidate, decision_model):
                continue

            # Audit and reconcile requirement kind against semantic contradictions
            reconciled_kind = _audit_and_reconcile_requirement_kind(
                kind=candidate.kind,
                description=candidate.description,
            )

            # Enforce deduplication (preserves distinct requirements for same target)
            norm_desc = " ".join(candidate.description.strip().lower().split())
            target_key = (candidate.target_entity_id, reconciled_kind, norm_desc)
            if target_key in seen_targets:
                continue
            seen_targets.add(target_key)

            # Enforce query policy based on reconciled EvidenceKind
            if reconciled_kind == EvidenceKind.EXTERNAL_RESEARCH:
                # Retain clean, non-empty search queries up to max 5
                queries = [q.strip() for q in candidate.suggested_queries if q and q.strip()][:5]
                if not queries:
                    clean_desc_query = " ".join(candidate.description.strip().split())[:100]
                    queries = [clean_desc_query]
            else:
                # Deterministic policy: suggested_queries MUST be [] for internal, user, or math
                queries = []

            # Construct canonical EvidenceRequirement
            req_id = f"req_{req_counter}"
            req_counter += 1

            req = EvidenceRequirement(
                id=req_id,
                target_entity_id=candidate.target_entity_id,
                target_entity_type=candidate.target_entity_type,
                kind=reconciled_kind,
                description=candidate.description.strip(),
                priority=candidate.priority,
                status=RequirementStatus.PENDING,  # Strictly initialized to PENDING
                suggested_queries=queries,
            )
            requirements.append(req)

        return requirements
