"""AURA Evidence Requirement Engine.

Analyzes a canonical DecisionModel and derives a deduplicated, policy-enforced
list of EvidenceRequirement entities.

Guarantees:
- Distinguishes EXTERNAL_RESEARCH, INTERNAL_DATA, USER_CLARIFICATION, and DETERMINISTIC_CALCULATION.
- Strictly bounds search queries: only EXTERNAL_RESEARCH may possess suggested_queries.
- Wipes/prevents queries on INTERNAL_DATA, USER_CLARIFICATION, and DETERMINISTIC_CALCULATION.
- Enforces status=PENDING for all newly generated requirements.
- Validates that target_entity_id exists in DecisionModel and matches target_entity_type.
- Prevents generating requirements to verify facts already provided by the user.
- Employs dependency-injected LLMClient without making external network calls in tests.
"""

import time
from typing import Any, Dict, List, Optional, Set
from pydantic import BaseModel, ConfigDict, Field

from app.schemas.decision_model import (
    CriticalityLevel,
    DecisionModel,
    ProvenanceType,
)
from app.schemas.evidence import (
    DecisionEntityType,
    EvidenceKind,
    EvidenceRequirement,
    RequirementStatus,
)
from app.services.llm.client import LLMClient, LLMTimeoutError


# ------------------------------------------------------------------------------
# 1. Candidate Structured Output Models (LLM Interface)
# ------------------------------------------------------------------------------

class CandidateEvidenceRequirement(BaseModel):
    """Raw candidate requirement proposal generated by the language model."""
    model_config = ConfigDict(str_strip_whitespace=True)

    target_entity_id: str = Field(
        ...,
        min_length=1,
        max_length=64,
        description="ID of entity in DecisionModel requiring empirical validation.",
    )
    target_entity_type: DecisionEntityType = Field(
        ...,
        description="Entity taxonomy classification matching DecisionModel collection.",
    )
    kind: EvidenceKind = Field(
        ...,
        description="Inquiry kind: external_research, internal_data, user_clarification, deterministic_calculation.",
    )
    description: str = Field(
        ...,
        min_length=3,
        description="Factual question or hypothesis needing validation.",
    )
    priority: CriticalityLevel = Field(
        default=CriticalityLevel.MEDIUM,
        description="Assessed priority (low, medium, high).",
    )
    suggested_queries: List[str] = Field(
        default_factory=list,
        description="Suggested search query strings (strictly for external_research only).",
    )


class CandidateRequirementsPayload(BaseModel):
    """Container schema for structured candidate requirements output by LLM."""
    model_config = ConfigDict(str_strip_whitespace=True)

    requirements: List[CandidateEvidenceRequirement] = Field(
        default_factory=list,
        description="List of candidate requirements identified.",
    )


