REQUIREMENTS_SYSTEM_PROMPT = """You are AURA's Evidence Requirement Analyst.
Your objective is to analyze a structured DecisionModel and determine what empirical information, data points, or calculations are strictly required to resolve the decision under uncertainty.

For each requirement:
1. Target an explicit existing entity from the DecisionModel (using its exact target_entity_id and target_entity_type).
   Valid entity types: 'assumption', 'unknown', 'variable', 'constraint', 'tradeoff', 'objective'.
2. Classify the inquiry into exactly ONE EvidenceKind:
   - EXTERNAL_RESEARCH: Public benchmarks, industry reports, academic literature, competitor data, or external market studies.
     May provide 1-3 concise, neutral, factual search queries.
     Do NOT write leading or confirmation-bias queries.
   - INTERNAL_DATA: Private, organization-specific metrics or historical records (e.g. internal CAC, current churn, internal margins, conversion rates, customer counts).
     MUST NOT provide search queries.
   - USER_CLARIFICATION: Subjective preferences, strategic risk tolerance, definitions, or intentions of the decision-maker.
     MUST NOT provide search queries.
   - DETERMINISTIC_CALCULATION: Mathematical transformations or arithmetic relationships (e.g. break-even volume increase, margin threshold math).
     Do NOT perform the calculation. MUST NOT provide search queries.
3. Provenance Rule:
   - Do NOT create requirements to verify facts already provided by the user (e.g., if the user stated a 20% discount or a specific constraint, do not create a requirement asking to verify that the value is 20%).
4. Do NOT make recommendations or propose a final decision.
"""


def build_requirements_prompt(model: DecisionModel) -> str:
    """Constructs prompt for evidence requirement extraction from DecisionModel."""
    sections: List[str] = [
        f"Decision Problem:\n{model.decision.summary}",
        "Primary Objective:\n" + "\n".join(f"- {o.id}: {o.description}" for o in model.objectives if o.is_primary),
    ]

    if model.assumptions:
        sections.append("Assumptions Needing Falsification/Validation:\n" + "\n".join(
            f"- {a.id} ({a.confidence.value}): {a.statement}" for a in model.assumptions
        ))

    if model.unknowns:
        sections.append("Identified Empirical Unknowns:\n" + "\n".join(
            f"- {u.id} (priority: {u.criticality.value}): {u.question}" for u in model.unknowns
        ))

    unresolved_vars = [v for v in model.variables if v.baseline_value is None or v.proposed_value is None]
    if unresolved_vars:
        sections.append("Unresolved / Inferred Variables:\n" + "\n".join(
            f"- {v.id}: {v.name} - {v.description} (baseline: {v.baseline_value or 'unknown'}, proposed: {v.proposed_value or 'unknown'}, provenance: {v.provenance.value})"
            for v in unresolved_vars
        ))

    user_vars = [v for v in model.variables if v.proposed_provenance == ProvenanceType.USER_PROVIDED and v.proposed_value is not None]
    if user_vars:
        sections.append("User-Provided Facts (DO NOT generate requirements to verify these values):\n" + "\n".join(
            f"- {v.id}: {v.name} = {v.proposed_value} {v.unit or ''} (user provided)"
            for v in user_vars
        ))

    if model.constraints:
        sections.append("Constraints:\n" + "\n".join(
            f"- {c.id}: {c.name} - {c.description} (source: {c.source}, hard: {c.is_hard_constraint})"
            for c in model.constraints
        ))

    sections.append("Analyze the decision entities above and output the candidate evidence requirements.")
    return "\n\n".join(sections)


