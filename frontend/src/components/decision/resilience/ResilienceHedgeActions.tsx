"use client";

import React from "react";

interface ResilienceHedgeActionsProps {
  recommendedHedges?: string[] | null;
  recommendationActionCount?: number;
}

export function ResilienceHedgeActions({
  recommendedHedges,
  recommendationActionCount,
}: ResilienceHedgeActionsProps) {
  const rawHedges = Array.isArray(recommendedHedges) ? recommendedHedges : [];

  // Deduplicate and filter non-empty string entries
  const uniqueHedges = Array.from(
    new Set(
      rawHedges
        .filter((h): h is string => typeof h === "string" && h.trim().length > 0)
        .map((h) => h.trim())
    )
  );

  const hasHedges = uniqueHedges.length > 0;

  return (
    <div
      aria-label="Recommended Hedges & Contingencies Section"
      className="rounded-2xl border border-zinc-800/90 bg-zinc-950/70 p-6 sm:p-7 text-zinc-100 shadow-md space-y-5 print:bg-white print:border-zinc-300 print:text-black"
    >
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3 pb-4 border-b border-zinc-800/80 print:border-zinc-300">
        <div>
          <span className="text-[11px] font-mono uppercase tracking-wider text-cyan-400 print:text-zinc-700 font-semibold">
            Proactive Risk-Containment Strategy
          </span>
          <h3 className="text-lg font-semibold text-white print:text-black tracking-tight mt-0.5">
            Recommended Resilience Hedges
          </h3>
        </div>

        <span
          className={`inline-flex items-center rounded-md border px-2.5 py-1 text-xs font-mono font-medium ${
            hasHedges
              ? "border-cyan-800/60 bg-cyan-950/40 text-cyan-300 print:bg-zinc-100 print:text-black print:border-zinc-300"
              : "border-zinc-800 bg-zinc-900 text-zinc-400 print:bg-zinc-100 print:text-black print:border-zinc-300"
          }`}
        >
          {hasHedges ? `${uniqueHedges.length} Hedges Suggested` : "0 Hedges"}
        </span>
      </div>

      {/* Distinction callout: Distinguish from Stage 4 recommendation actions */}
      <div className="rounded-xl border border-cyan-900/40 bg-cyan-950/20 p-4 text-xs text-cyan-200 print:bg-zinc-50 print:border-zinc-300 print:text-black flex items-start gap-3">
        <svg
          className="h-4 w-4 text-cyan-400 print:text-zinc-700 shrink-0 mt-0.5"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth="2"
          strokeLinecap="round"
          strokeLinejoin="round"
          aria-hidden="true"
        >
          <path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z" />
        </svg>
        <div className="space-y-1 leading-relaxed">
          <p className="font-semibold text-cyan-300 print:text-black">
            Distinction from Baseline Recommendation Actions:
          </p>
          <p className="text-zinc-300 print:text-zinc-700">
            These hedge recommendations are protective risk-containment controls generated by the deterministic Resilience Engine. They specifically protect against adverse pessimistic scenarios, irreversible commitments, or unhedged hard constraints. They complement
            {recommendationActionCount ? ` the ${recommendationActionCount} primary execution actions in Stage 4` : " the primary recommendation action plan"}
            {" "}without replacing them.
          </p>
        </div>
      </div>

      {/* Hedge Items List */}
      {hasHedges ? (
        <ol className="space-y-3" aria-label="Recommended hedges list">
          {uniqueHedges.map((hedge, idx) => (
            <li
              key={idx}
              className="rounded-xl border border-zinc-800 bg-zinc-900/40 p-4 text-xs text-zinc-200 print:bg-zinc-50 print:border-zinc-300 print:text-black space-y-2 hover:border-zinc-700 transition-colors"
            >
              <div className="flex items-center justify-between gap-3">
                <div className="flex items-center gap-2">
                  <span className="flex items-center justify-center h-5 w-16 rounded bg-cyan-950/80 border border-cyan-800/80 text-cyan-300 font-mono text-[10px] font-bold uppercase print:bg-zinc-200 print:text-black print:border-zinc-400">
                    HEDGE-{String(idx + 1).padStart(2, "0")}
                  </span>
                  <span className="text-[11px] font-mono text-zinc-400 print:text-zinc-600">
                    Resilience Guardrail
                  </span>
                </div>

                {/* Explicitly NOT labeled as completed or verified */}
                <span className="text-[10px] font-mono px-2 py-0.5 rounded border border-zinc-700/80 bg-zinc-800/80 text-zinc-300 print:bg-zinc-100 print:text-black">
                  Suggested Action
                </span>
              </div>

              <p className="text-xs sm:text-sm text-zinc-100 print:text-black leading-relaxed font-sans pl-1">
                {hedge}
              </p>
            </li>
          ))}
        </ol>
      ) : (
        /* Empty State */
        <div className="rounded-xl border border-zinc-800 bg-zinc-900/30 p-5 text-xs text-zinc-400 print:bg-zinc-50 print:border-zinc-300 print:text-black text-center">
          No additional proactive hedges recommended. Current strategy and contingency coverage provide sufficient resilience buffer.
        </div>
      )}
    </div>
  );
}
